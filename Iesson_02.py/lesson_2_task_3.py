#Напишите функцию square, принимающую один аргумент — сторону квадрата — 
# и возвращающую площадь квадрата.


import math

def square(side):
    
    area = side ** 2  # Площадь квадрата
    
    # Если сторона была не целым числом (float), округляем площадь вверх
    if isinstance(side, float):
        return math.ceil(area)
    
    # Если сторона целая (int), возвращаем площадь как есть
    return area

print(square(5))      # Целое число: 5 * 5 = 25
print(square(4.1))    # Дробное число: 4.1 * 4.1 = 16.81 -> округление вверх до 17
print(square(3.0))    # Дробное число: 3.0 * 3.0 = 9.0 -> округление вверх до 9
